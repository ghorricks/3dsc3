def font_bytes():
    out=bytearray()
    for c in range(32,96):
        rows=[r.strip() for r in G[chr(c)]]
        assert len(rows)==7 and all(len(r)==7 for r in rows),(chr(c),rows)
        for r in rows: out.append(int(r.replace('#','1').replace('.','0')+'0',2))
        out.append(0)
    return bytes(out)
